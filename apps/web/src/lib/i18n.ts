export type MessageKey = keyof (typeof dict)['vi'];

export function t(locale: Locale, key: MessageKey): string {
  return dict[locale][key] ?? key;
}

export function getLocale(searchParams?: Record<string, string | string[] | undefined> | null): Locale {
  const lang = searchParams?.lang;
  const val = Array.isArray(lang) ? lang[0] : lang;
  return val === 'en' ? 'en' : 'vi';
}

/** Client-side hook: reads locale from cookie, falls back to 'vi' */
export function useLocale(): Locale {
  if (typeof document === 'undefined') return 'vi';
  const match = document.cookie.match(/(?:^|;\s*)tvp_lang=([^;]*)/);
  return match?.[1] === 'en' ? 'en' : 'vi';
}
